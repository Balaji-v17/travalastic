import React, { useState, useEffect, useRef, useCallback } from 'react';
import { useApp } from '../../store/AppContext';
import {
  getDisruptionApi,
  generateProposalApi,
  approveDisruptionApi,
  dismissDisruptionApi,
  undoDisruptionApi,
  type DisruptionItem,
} from '../../lib/disruptionsApi';
import {
  viewStateFor,
  resolveActivityTitle,
  formatDelay,
  reminderLines,
} from '../../lib/disruptionView';

interface DisruptionReviewModalProps {
  isOpen: boolean;
  onClose: () => void;
  disruptionId: string | null;
  itineraryDays?: any[];
  triggerRef?: React.RefObject<HTMLElement | null>;
  onDisruptionUpdated?: () => void;
}

export default function DisruptionReviewModal({
  isOpen,
  onClose,
  disruptionId,
  itineraryDays = [],
  triggerRef,
  onDisruptionUpdated,
}: DisruptionReviewModalProps) {
  const { refreshJourneys, openTransport } = useApp();

  const [disruption, setDisruption] = useState<DisruptionItem | null>(null);
  const [loading, setLoading] = useState(true);
  const [loadError, setLoadError] = useState<string | null>(null);
  const [actionLoading, setActionLoading] = useState(false);
  const [actionError, setActionError] = useState<{ code: string; message: string } | null>(null);
  const [generatingProposal, setGeneratingProposal] = useState(false);

  const modalRef = useRef<HTMLDivElement>(null);
  const previouslyFocusedElementRef = useRef<HTMLElement | null>(null);
  const hasAutoGeneratedRef = useRef<string | null>(null);

  // Load disruption details when modal opens
  const fetchDetails = useCallback(async () => {
    if (!disruptionId) {
      setLoading(false);
      return;
    }

    setLoading(true);
    setLoadError(null);
    setActionError(null);

    try {
      const data = await getDisruptionApi(disruptionId);
      setDisruption(data);
    } catch (err: any) {
      setLoadError(err?.message || 'Unable to load disruption details.');
    } finally {
      setLoading(false);
    }
  }, [disruptionId]);

  useEffect(() => {
    if (isOpen) {
      fetchDetails();
    } else {
      setDisruption(null);
      setActionError(null);
      setLoadError(null);
      hasAutoGeneratedRef.current = null;
    }
  }, [isOpen, fetchDetails]);

  // Proposal generation handler (auto once for 'new', and manual on 'Make a new plan')
  const handleGenerateProposal = useCallback(
    async (regenerate = false) => {
      if (!disruptionId || generatingProposal) return;
      setGeneratingProposal(true);
      setActionError(null);

      try {
        const result = await generateProposalApi(disruptionId, { regenerate });
        if (result?.proposal) {
          setDisruption((prev) =>
            prev
              ? {
                  ...prev,
                  status: (result.status as any) || 'proposed',
                  proposal: result.proposal,
                }
              : null
          );
        } else {
          const refreshed = await getDisruptionApi(disruptionId);
          setDisruption(refreshed);
        }
      } catch (err: any) {
        setActionError({
          code: err?.code || 'error',
          message: err?.message || 'Could not generate a new plan right now.',
        });
      } finally {
        setGeneratingProposal(false);
      }
    },
    [disruptionId, generatingProposal]
  );

  // Auto-generate proposal when status is 'new' (only once per disruptionId)
  useEffect(() => {
    if (
      isOpen &&
      disruption &&
      disruption.status === 'new' &&
      hasAutoGeneratedRef.current !== disruption.id &&
      !generatingProposal
    ) {
      hasAutoGeneratedRef.current = disruption.id;
      handleGenerateProposal(false);
    }
  }, [isOpen, disruption, generatingProposal, handleGenerateProposal]);

  // Approve action
  const handleApprove = async () => {
    if (!disruptionId || actionLoading) return;
    const baseHash = disruption?.proposal?.baseHash;
    if (!baseHash) {
      setActionError({
        code: 'missing_hash',
        message: 'No proposal base hash available. Please generate a new plan.',
      });
      return;
    }

    setActionLoading(true);
    setActionError(null);

    try {
      const res = await approveDisruptionApi(disruptionId, baseHash);
      if (res?.disruption) {
        setDisruption(res.disruption);
      } else {
        const refreshed = await getDisruptionApi(disruptionId);
        setDisruption(refreshed);
      }
      // Refresh journey cache
      await refreshJourneys();
      onDisruptionUpdated?.();
    } catch (err: any) {
      setActionError({
        code: err?.code || 'error',
        message: err?.message || 'Could not apply schedule changes.',
      });
    } finally {
      setActionLoading(false);
    }
  };

  // Dismiss action
  const handleDismiss = async () => {
    if (!disruptionId || actionLoading) return;

    setActionLoading(true);
    setActionError(null);

    try {
      const res = await dismissDisruptionApi(disruptionId);
      if (res?.disruption) {
        setDisruption(res.disruption);
      } else {
        const refreshed = await getDisruptionApi(disruptionId);
        setDisruption(refreshed);
      }
      await refreshJourneys();
      onDisruptionUpdated?.();
    } catch (err: any) {
      setActionError({
        code: err?.code || 'error',
        message: err?.message || 'Could not dismiss disruption.',
      });
    } finally {
      setActionLoading(false);
    }
  };

  // Undo action
  const handleUndo = async () => {
    if (!disruptionId || actionLoading) return;

    setActionLoading(true);
    setActionError(null);

    try {
      const res = await undoDisruptionApi(disruptionId);
      if (res?.disruption) {
        setDisruption(res.disruption);
      } else {
        const refreshed = await getDisruptionApi(disruptionId);
        setDisruption(refreshed);
      }
      await refreshJourneys();
      onDisruptionUpdated?.();
    } catch (err: any) {
      setActionError({
        code: err?.code || 'error',
        message: err?.message || 'Could not undo schedule changes.',
      });
    } finally {
      setActionLoading(false);
    }
  };

  // Accessibility: Focus trap & Escape key
  useEffect(() => {
    if (!isOpen) return;

    previouslyFocusedElementRef.current = (document.activeElement as HTMLElement) || null;
    const timer = setTimeout(() => {
      const focusable = modalRef.current?.querySelectorAll<HTMLElement>(
        'button:not([disabled]), [href], input:not([disabled]), select:not([disabled]), textarea:not([disabled]), [tabindex]:not([tabindex="-1"])'
      );
      if (focusable && focusable.length > 0) {
        focusable[0].focus();
      } else {
        modalRef.current?.focus();
      }
    }, 50);

    const handleKeyDown = (e: KeyboardEvent) => {
      if (e.key === 'Escape') {
        if (!actionLoading && !generatingProposal) {
          onClose();
        }
        return;
      }

      if (e.key === 'Tab') {
        const focusable = modalRef.current?.querySelectorAll<HTMLElement>(
          'button:not([disabled]), [href], input:not([disabled]), select:not([disabled]), textarea:not([disabled]), [tabindex]:not([tabindex="-1"])'
        );
        if (!focusable || focusable.length === 0) return;

        const first = focusable[0];
        const last = focusable[focusable.length - 1];

        if (e.shiftKey) {
          if (document.activeElement === first) {
            e.preventDefault();
            last.focus();
          }
        } else {
          if (document.activeElement === last) {
            e.preventDefault();
            first.focus();
          }
        }
      }
    };

    window.addEventListener('keydown', handleKeyDown);
    return () => {
      clearTimeout(timer);
      window.removeEventListener('keydown', handleKeyDown);
      if (triggerRef?.current) {
        triggerRef.current.focus();
      } else if (previouslyFocusedElementRef.current) {
        previouslyFocusedElementRef.current.focus();
      }
    };
  }, [isOpen, actionLoading, generatingProposal, onClose, triggerRef]);

  if (!isOpen) return null;

  const viewState = viewStateFor(disruption);
  const isSimulated = disruption?.simulated || disruption?.source === 'simulation';
  const proposal = disruption?.proposal;
  const changes = Array.isArray(proposal?.changes) ? proposal.changes : [];
  const movedChanges = changes.filter((c) => c.action === 'move');
  const skippedChanges = changes.filter((c) => c.action === 'skip' || c.action === 'drop');
  const unchangedCount =
    typeof proposal?.unchangedCount === 'number'
      ? proposal.unchangedCount
      : changes.filter((c) => c.action === 'keep').length;

  return (
    <div
      className="fixed inset-0 z-50 overflow-y-auto bg-black/60 backdrop-blur-xs flex items-end sm:items-center justify-center p-0 sm:p-4 animate-fade-in"
      onClick={(e) => {
        if (e.target === e.currentTarget && !actionLoading && !generatingProposal) {
          onClose();
        }
      }}
    >
      <div
        ref={modalRef}
        role="dialog"
        aria-modal="true"
        aria-labelledby="disruption-modal-title"
        tabIndex={-1}
        className="w-full sm:max-w-2xl bg-white rounded-t-2xl sm:rounded-2xl shadow-2xl border border-slate-200 overflow-hidden flex flex-col max-h-[92vh] sm:max-h-[85vh] animate-slide-up focus:outline-hidden"
      >
        {/* Header */}
        <div className="px-6 py-4 border-b border-slate-100 flex items-center justify-between bg-slate-50/50">
          <div className="flex items-center gap-3">
            <div className="w-9 h-9 rounded-xl bg-amber-100 flex items-center justify-center text-lg shrink-0">
              ✈️
            </div>
            <div>
              <h2
                id="disruption-modal-title"
                className="font-display text-xl text-slate-900 leading-snug"
              >
                Flight Schedule Change
              </h2>
              <p className="text-xs text-slate-500 font-medium">
                {disruption?.details?.delayMinutes
                  ? `Delay: ${disruption.details.delayMinutes} minutes`
                  : 'Airline initiated schedule update'}
              </p>
            </div>
          </div>
          <button
            type="button"
            onClick={onClose}
            disabled={actionLoading || generatingProposal}
            aria-label="Close dialog"
            className="w-10 h-10 min-h-[44px] min-w-[44px] rounded-xl flex items-center justify-center text-slate-400 hover:text-slate-600 hover:bg-slate-100 transition-colors disabled:opacity-50"
          >
            ✕
          </button>
        </div>

        {/* Content Body */}
        <div className="p-6 overflow-y-auto space-y-5">
          {/* Source Honesty Banner */}
          {isSimulated ? (
            <div className="p-4 rounded-xl bg-amber-50 border border-amber-200 flex flex-col gap-2">
              <div className="flex items-center gap-2">
                <span className="px-2.5 py-0.5 rounded-full text-xs font-bold uppercase tracking-wider bg-amber-100 text-amber-900 border border-amber-300">
                  SIMULATED
                </span>
                <span className="text-xs font-semibold text-amber-800">Demo Simulation</span>
              </div>
              <p className="text-sm text-slate-700">
                This is a demo. Applying it changes your saved itinerary, and you can undo it.
              </p>
            </div>
          ) : (
            <div className="p-3.5 rounded-xl bg-slate-50 border border-slate-200">
              <p className="text-sm text-slate-600">
                Based on a schedule change reported by your airline.
              </p>
            </div>
          )}

          {/* Loading initial disruption data */}
          {loading && (
            <div className="py-12 text-center space-y-3">
              <div className="w-8 h-8 border-3 border-amber-600 border-t-transparent rounded-full animate-spin mx-auto" />
              <p className="text-sm text-slate-600 font-medium">Loading flight disruption details…</p>
            </div>
          )}

          {/* Initial load error */}
          {loadError && !loading && (
            <div className="p-5 rounded-xl bg-red-50 border border-red-200 text-center space-y-3">
              <p className="text-sm text-red-700 font-medium">{loadError}</p>
              <button
                type="button"
                onClick={fetchDetails}
                className="px-4 py-2 min-h-[44px] bg-red-600 text-white text-sm font-semibold rounded-xl hover:bg-red-700 transition-colors"
              >
                Retry
              </button>
            </div>
          )}

          {/* State: GENERATING / 'new' */}
          {!loading && !loadError && (viewState === 'generating' || generatingProposal) && (
            <div className="py-10 px-4 text-center rounded-xl bg-slate-50 border border-slate-200 space-y-4">
              <div className="w-8 h-8 border-3 border-amber-600 border-t-transparent rounded-full animate-spin mx-auto" />
              <div>
                <h3 className="text-base font-semibold text-slate-900">Working out a new plan…</h3>
                <p className="text-sm text-slate-500 mt-1">
                  Adjusting remaining activities for your updated flight arrival time.
                </p>
              </div>

              {actionError && (
                <div
                  aria-live="polite"
                  className="p-4 rounded-xl bg-red-50 border border-red-200 text-left space-y-2 mt-4"
                >
                  <p className="text-sm text-red-700 font-medium">{actionError.message}</p>
                  <button
                    type="button"
                    onClick={() => handleGenerateProposal(false)}
                    className="px-4 py-2 min-h-[44px] bg-red-600 text-white text-sm font-semibold rounded-xl hover:bg-red-700 transition-colors"
                  >
                    Retry
                  </button>
                </div>
              )}
            </div>
          )}

          {/* State: REVIEW (Reschedule or Manual Review) */}
          {!loading &&
            !loadError &&
            (viewState === 'review' || viewState === 'manual_review') &&
            !generatingProposal && (
              <div className="space-y-5">
                {/* Proposal Summary verbatim */}
                {proposal?.summary && (
                  <div className="p-4 rounded-xl bg-blue-50/70 border border-blue-100">
                    <p className="text-xs font-bold uppercase tracking-wider text-blue-900 mb-1">
                      Suggested Plan
                    </p>
                    <p className="text-sm text-slate-800 leading-relaxed">{proposal.summary}</p>
                  </div>
                )}

                {/* Reschedule Changes Breakdown */}
                {viewState === 'review' && (
                  <div className="space-y-4">
                    {/* Moved Activities */}
                    {movedChanges.length > 0 && (
                      <div className="rounded-xl border border-slate-200 overflow-hidden">
                        <div className="px-4 py-2.5 bg-slate-50 border-b border-slate-200 font-semibold text-sm text-slate-800 flex items-center justify-between">
                          <span>Moved Activities</span>
                          <span className="text-xs text-amber-700 bg-amber-50 px-2 py-0.5 rounded-full border border-amber-200">
                            {movedChanges.length} shifted
                          </span>
                        </div>
                        <div className="divide-y divide-slate-100">
                          {movedChanges.map((change, idx) => {
                            const title = resolveActivityTitle(change.activityId, itineraryDays);
                            return (
                              <div key={`moved-${change.activityId || idx}`} className="p-4">
                                <div className="flex items-start justify-between gap-3">
                                  <div>
                                    <h4 className="font-semibold text-slate-900 text-sm">{title}</h4>
                                    <p className="text-xs text-amber-700 font-medium mt-0.5">
                                      {change.fromTime || 'Original'} → {change.toTime || 'Updated'}
                                    </p>
                                  </div>
                                </div>
                                {change.reason && (
                                  <p className="text-xs text-slate-500 mt-2 leading-relaxed">
                                    {change.reason}
                                  </p>
                                )}
                              </div>
                            );
                          })}
                        </div>
                      </div>
                    )}

                    {/* Skipped Activities */}
                    {skippedChanges.length > 0 && (
                      <div className="rounded-xl border border-slate-200 overflow-hidden">
                        <div className="px-4 py-2.5 bg-slate-50 border-b border-slate-200 font-semibold text-sm text-slate-800 flex items-center justify-between">
                          <span>Skipped Activities</span>
                          <span className="text-xs text-red-700 bg-red-50 px-2 py-0.5 rounded-full border border-red-200">
                            {skippedChanges.length} dropped
                          </span>
                        </div>
                        <div className="divide-y divide-slate-100">
                          {skippedChanges.map((change, idx) => {
                            const title = resolveActivityTitle(change.activityId, itineraryDays);
                            return (
                              <div key={`skipped-${change.activityId || idx}`} className="p-4">
                                <h4 className="font-semibold text-slate-900 text-sm">{title}</h4>
                                <span className="inline-block mt-1 text-xs text-red-600 font-medium">
                                  Skipped due to delay
                                </span>
                                {change.reason && (
                                  <p className="text-xs text-slate-500 mt-1 leading-relaxed">
                                    {change.reason}
                                  </p>
                                )}
                              </div>
                            );
                          })}
                        </div>
                      </div>
                    )}

                    {/* Unchanged Activities Count */}
                    {unchangedCount > 0 && (
                      <div className="px-4 py-3 rounded-xl bg-slate-50 border border-slate-200 text-sm text-slate-600 flex items-center gap-2">
                        <span className="text-emerald-600 font-bold">✓</span>
                        <span>
                          {unchangedCount} {unchangedCount === 1 ? 'activity' : 'activities'} unchanged
                        </span>
                      </div>
                    )}
                  </div>
                )}

                {/* Check your pickup Reminder Block */}
                <div className="p-4 rounded-xl bg-slate-50 border border-slate-200 space-y-2.5 text-left">
                  <div className="flex items-center justify-between">
                    <div className="flex items-center gap-2">
                      <span className="text-base leading-none">🚕</span>
                      <h4 className="text-sm font-semibold text-slate-900">Check your pickup</h4>
                    </div>
                    {disruption?.details?.delayMinutes != null &&
                      !disruption?.details?.structural && (
                        <span className="text-xs font-medium text-slate-600 bg-white px-2 py-0.5 rounded-md border border-slate-200">
                          +{formatDelay(disruption.details.delayMinutes)}
                        </span>
                      )}
                  </div>
                  <div className="space-y-1.5 text-xs text-slate-700 leading-relaxed">
                    {reminderLines(disruption?.details).map((line, idx) => (
                      <p key={idx}>{line}</p>
                    ))}
                  </div>
                  <div className="pt-2">
                    <button
                      type="button"
                      onClick={() => {
                        onClose();
                        openTransport('cab');
                      }}
                      className="inline-flex items-center gap-1.5 px-3 py-1.5 bg-slate-900 hover:bg-slate-800 text-white text-xs font-semibold rounded-lg transition-colors cursor-pointer"
                    >
                      <span>Open cab options</span>
                      <span>↗</span>
                    </button>
                    <p className="text-[11px] text-slate-500 mt-1">Nothing is booked or changed for you.</p>
                  </div>
                </div>

                {/* Scope Note */}
                <div className="p-4 rounded-xl bg-amber-50/60 border border-amber-200/70 text-xs text-amber-900 leading-relaxed flex items-start gap-2.5">
                  <span className="text-base leading-none">ℹ️</span>
                  <p>
                    I only adjust activity times in your itinerary. Your cab, hotel check-in and any
                    reservations are not changed, so check them yourself.
                  </p>
                </div>

                {/* Inline Action Errors */}
                {actionError && (
                  <div
                    aria-live="polite"
                    className="p-4 rounded-xl bg-red-50 border border-red-200 text-sm space-y-2"
                  >
                    <p className="text-red-700 font-medium">
                      {actionError.code === 'proposal_changed' ||
                      actionError.code === 'itinerary_changed'
                        ? 'Your itinerary changed since this plan was made'
                        : actionError.code === '429' || actionError.code === 'rate_limit'
                        ? 'Too many requests, try again in a bit'
                        : actionError.message}
                    </p>

                    {(actionError.code === 'proposal_changed' ||
                      actionError.code === 'itinerary_changed') && (
                      <button
                        type="button"
                        onClick={() => handleGenerateProposal(true)}
                        disabled={generatingProposal}
                        className="px-4 py-2 min-h-[44px] bg-red-600 text-white text-xs font-semibold rounded-xl hover:bg-red-700 transition-colors"
                      >
                        Make a new plan
                      </button>
                    )}
                  </div>
                )}

                {/* Action Buttons for Reschedule */}
                {viewState === 'review' && (
                  <div className="pt-2 flex flex-col sm:flex-row gap-3">
                    <button
                      type="button"
                      onClick={handleApprove}
                      disabled={actionLoading || generatingProposal}
                      className="flex-1 px-5 py-3 min-h-[44px] bg-amber-600 hover:bg-amber-700 text-white text-sm font-semibold rounded-xl transition-colors shadow-xs disabled:opacity-50 text-center"
                    >
                      {actionLoading ? 'Applying…' : 'Apply these changes'}
                    </button>
                    <button
                      type="button"
                      onClick={handleDismiss}
                      disabled={actionLoading || generatingProposal}
                      className="px-5 py-3 min-h-[44px] border border-slate-200 text-slate-700 text-sm font-medium rounded-xl hover:bg-slate-50 transition-colors disabled:opacity-50 text-center"
                    >
                      Keep my itinerary as is
                    </button>
                  </div>
                )}

                {/* Action Buttons for Manual Review (NO Apply button) */}
                {viewState === 'manual_review' && (
                  <div className="pt-2 flex flex-col sm:flex-row gap-3">
                    <button
                      type="button"
                      onClick={onClose}
                      className="flex-1 px-5 py-3 min-h-[44px] bg-blue-600 hover:bg-blue-700 text-white text-sm font-semibold rounded-xl transition-colors text-center"
                    >
                      Review my itinerary
                    </button>
                    <button
                      type="button"
                      onClick={handleDismiss}
                      disabled={actionLoading}
                      className="px-5 py-3 min-h-[44px] border border-slate-200 text-slate-700 text-sm font-medium rounded-xl hover:bg-slate-50 transition-colors text-center disabled:opacity-50"
                    >
                      Dismiss
                    </button>
                  </div>
                )}
              </div>
            )}

          {/* State: APPLIED */}
          {!loading && !loadError && viewState === 'applied' && (
            <div className="py-6 space-y-5 text-center">
              <div className="w-12 h-12 bg-emerald-100 text-emerald-600 rounded-full flex items-center justify-center text-2xl mx-auto">
                ✓
              </div>
              <div>
                <h3 className="text-xl font-display text-slate-900">Changes applied</h3>
                <p className="text-sm text-slate-600 mt-1">
                  Your itinerary activities have been shifted for the flight delay.
                </p>
              </div>

              {/* Check your pickup Reminder Block */}
              <div className="p-4 rounded-xl bg-slate-50 border border-slate-200 space-y-2.5 text-left">
                <div className="flex items-center justify-between">
                  <div className="flex items-center gap-2">
                    <span className="text-base leading-none">🚕</span>
                    <h4 className="text-sm font-semibold text-slate-900">Check your pickup</h4>
                  </div>
                  {disruption?.details?.delayMinutes != null &&
                    !disruption?.details?.structural && (
                      <span className="text-xs font-medium text-slate-600 bg-white px-2 py-0.5 rounded-md border border-slate-200">
                        +{formatDelay(disruption.details.delayMinutes)}
                      </span>
                    )}
                </div>
                <div className="space-y-1.5 text-xs text-slate-700 leading-relaxed">
                  {reminderLines(disruption?.details).map((line, idx) => (
                    <p key={idx}>{line}</p>
                  ))}
                </div>
                <div className="pt-2">
                  <button
                    type="button"
                    onClick={() => {
                      onClose();
                      openTransport('cab');
                    }}
                    className="inline-flex items-center gap-1.5 px-3 py-1.5 bg-slate-900 hover:bg-slate-800 text-white text-xs font-semibold rounded-lg transition-colors cursor-pointer"
                  >
                    <span>Open cab options</span>
                    <span>↗</span>
                  </button>
                  <p className="text-[11px] text-slate-500 mt-1">Nothing is booked or changed for you.</p>
                </div>
              </div>

              {/* Scope Note */}
              <div className="p-4 rounded-xl bg-amber-50/60 border border-amber-200/70 text-xs text-amber-900 text-left leading-relaxed">
                I only adjust activity times in your itinerary. Your cab, hotel check-in and any
                reservations are not changed, so check them yourself.
              </div>

              {/* Action Error on Undo */}
              {actionError && (
                <div
                  aria-live="polite"
                  className="p-4 rounded-xl bg-red-50 border border-red-200 text-sm text-left"
                >
                  <p className="text-red-700 font-medium">
                    {actionError.code === 'newer_changes_exist'
                      ? 'Other changes were made after this one. Undo those first.'
                      : actionError.code === 'too_old'
                      ? 'This change is too old to undo automatically.'
                      : actionError.code === '429' || actionError.code === 'rate_limit'
                      ? 'Too many requests, try again in a bit'
                      : actionError.message}
                  </p>
                </div>
              )}

              <div className="pt-2 flex flex-col sm:flex-row gap-3">
                <button
                  type="button"
                  onClick={handleUndo}
                  disabled={actionLoading}
                  className="flex-1 px-5 py-3 min-h-[44px] border border-amber-600 text-amber-700 hover:bg-amber-50 text-sm font-semibold rounded-xl transition-colors disabled:opacity-50 text-center"
                >
                  {actionLoading ? 'Undoing…' : 'Undo these changes'}
                </button>
                <button
                  type="button"
                  onClick={onClose}
                  className="px-5 py-3 min-h-[44px] bg-slate-900 text-white text-sm font-semibold rounded-xl hover:bg-slate-800 transition-colors text-center"
                >
                  Close
                </button>
              </div>
            </div>
          )}

          {/* State: CLOSED (reverted, dismissed, expired) */}
          {!loading && !loadError && viewState === 'closed' && (
            <div className="py-8 space-y-4 text-center">
              <div className="w-12 h-12 bg-slate-100 text-slate-500 rounded-full flex items-center justify-center text-xl mx-auto">
                {disruption?.status === 'reverted'
                  ? '↩'
                  : disruption?.status === 'dismissed'
                  ? '✕'
                  : '⏱'}
              </div>
              <div>
                <h3 className="text-lg font-semibold text-slate-900">
                  {disruption?.status === 'reverted'
                    ? 'You undid these changes'
                    : disruption?.status === 'dismissed'
                    ? 'You kept your itinerary'
                    : 'This change is no longer relevant'}
                </h3>
                <p className="text-sm text-slate-500 mt-1">
                  {disruption?.status === 'reverted'
                    ? 'Your itinerary was restored to its previous schedule.'
                    : disruption?.status === 'dismissed'
                    ? 'Your itinerary schedule remains unchanged.'
                    : 'The scheduled date for this travel segment has passed.'}
                </p>
              </div>
              <div className="pt-2">
                <button
                  type="button"
                  onClick={onClose}
                  className="px-6 py-2.5 min-h-[44px] bg-slate-900 text-white text-sm font-semibold rounded-xl hover:bg-slate-800 transition-colors"
                >
                  Close
                </button>
              </div>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}

